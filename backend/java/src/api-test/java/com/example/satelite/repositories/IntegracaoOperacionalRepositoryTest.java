package com.example.satelite.repositories;

import static org.junit.jupiter.api.Assertions.*;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import com.example.satelite.dto.auditoria.IndicadoresOperacionaisDTO;

class IntegracaoOperacionalRepositoryTest {
    JdbcTemplate jdbc;
    IntegracaoOperacionalRepository repository;
    IntegracaoEventoRepository eventos;
    @BeforeEach void preparar() {
        var ds = new DriverManagerDataSource("jdbc:h2:mem:operacional_"+UUID.randomUUID()+";MODE=MSSQLServer;DB_CLOSE_DELAY=-1","sa","");
        jdbc=new JdbcTemplate(ds); jdbc.execute("CREATE SCHEMA dbo");
        jdbc.execute("CREATE TABLE dbo.tb_confirmacao_comprovante(chave_nfe VARCHAR(44),chave_cte VARCHAR(44),primeira_confirmacao_em TIMESTAMP)");
        jdbc.execute("""
            CREATE TABLE dbo.tb_log_integracao(id BIGINT PRIMARY KEY, sistema_destino VARCHAR(20),occurrence_id BIGINT,
              chave_cte VARCHAR(44),chave_nfe VARCHAR(44),canhoto_chave_cte_efetiva VARCHAR(44),data_processamento TIMESTAMP,
              status_dados VARCHAR(50),status_canhoto VARCHAR(50),data_processamento_dados TIMESTAMP,data_processamento_canhoto TIMESTAMP,
              canhoto_classificacao_operacional VARCHAR(40),arquivado INT,mensagem_erro_dados VARCHAR(200),mensagem_erro_canhoto VARCHAR(200),
              dados_pendente_desde TIMESTAMP,canhoto_pendente_desde TIMESTAMP,dados_proxima_avaliacao_em TIMESTAMP,canhoto_proxima_avaliacao_em TIMESTAMP)
            """);
        jdbc.execute("""
            CREATE TABLE dbo.tb_integracao_etapa_evento(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              evento_id VARCHAR(36) UNIQUE,execucao_id VARCHAR(36),log_id BIGINT,sistema_destino VARCHAR(20),etapa VARCHAR(20),
              documento VARCHAR(128),tipo VARCHAR(30),acao VARCHAR(40),motivo VARCHAR(80),ocorrido_em TIMESTAMP,proxima_avaliacao_em TIMESTAMP)
            """);
        var named=new NamedParameterJdbcTemplate(ds); repository=new IntegracaoOperacionalRepository(named); eventos=new IntegracaoEventoRepository(named);
    }
    void log(long id,String cte,String nfe,String status,String motivo) {
        jdbc.update("""
            INSERT INTO dbo.tb_log_integracao(id,sistema_destino,chave_cte,chave_nfe,status_dados,status_canhoto,
              mensagem_erro_dados,data_processamento,data_processamento_dados,arquivado)
            VALUES (?,'VEDACIT',?,?,?,'NAO_APLICAVEL',?,'2026-09-21 12:00:00','2026-09-21 12:00:00',0)
            """,id,cte,nfe,status,motivo);
    }
    IndicadoresOperacionaisDTO consultar() { return repository.consultar(LocalDate.of(2026,9,1),LocalDate.of(2026,9,21),List.of("VEDACIT")); }
    IndicadoresOperacionaisDTO.Etapa xml() { return consultar().etapas().stream().filter(e->e.etapa().equals("DADOS")).findFirst().orElseThrow(); }
    void evento(String documento,String tipo,String acao,String quando) {
        eventos.registrar(new IntegracaoEventoRepository.Evento(UUID.randomUUID(),null,1L,"VEDACIT","DADOS",documento,tipo,acao,acao,LocalDateTime.parse(quando),null));
    }

    @Test void esperaDeAcessoNaoViraFalhaDiariaNemNovaTentativaDeEnvio() {
        for(int i=1;i<=160;i++) log(i,"cte"+i,"nf"+i,"ERRO_DESTINO",i<=17?"ORIGEM_XML_HTTP_401":"ORIGEM_XML_AUTENTICACAO_EM_ESPERA");
        assertEquals(160,xml().aguardandoOrigem()); assertEquals(0,xml().novaTentativa());
        assertTrue(consultar().evolucao().isEmpty()); assertNull(consultar().historicoDesde());
    }
    @Test void reavaliarOuConfirmarNaoMoveNemApagaEventosAnteriores() {
        log(1,"cte","nf","ERRO_DESTINO","ORIGEM_XML_HTTP_401");
        for(int i=0;i<10;i++) evento("CTE:cte","AVALIACAO","AGUARDANDO_ORIGEM",i<4?"2026-09-20T10:00:00":"2026-09-21T11:00:00");
        var antes=consultar(); assertEquals(1,xml().aguardandoOrigem()); assertEquals(4,antes.atividade().get(0).avaliacoes());
        assertEquals(6,antes.atividade().get(1).avaliacoes()); assertEquals(0,antes.atividade().get(1).enviosIniciados());
        jdbc.update("UPDATE dbo.tb_log_integracao SET status_dados='SUCESSO',mensagem_erro_dados=NULL");
        var depois=consultar(); assertEquals(antes.atividade(),depois.atividade());
        assertEquals(1,xml().sucessosPeriodo()); assertEquals(0,xml().aguardandoOrigem());
    }
    @Test void envioRepetidoConsideraEventoAnteriorAoPeriodoSemDuplicarTotal() {
        evento("CTE:cte","ENVIO_INICIADO","AGUARDANDO_CONFIRMACAO","2026-08-31T12:00:00");
        evento("CTE:cte","CONSULTA_ORIGEM","AGUARDANDO_CONFIRMACAO","2026-09-21T10:00:00");
        evento("CTE:cte","ENVIO_INICIADO","AGUARDANDO_CONFIRMACAO","2026-09-21T10:01:00");
        var a=consultar().atividade().get(0); assertEquals(1,a.enviosIniciados()); assertEquals(1,a.reenviosIniciados());
        assertEquals(1,a.consultasOrigem()); assertEquals(0,a.avaliacoes());
    }
    @Test void persistirMesmoEventoDuasVezesNaoDuplicaAuditoria() {
        var e=new IntegracaoEventoRepository.Evento(UUID.randomUUID(),UUID.randomUUID(),1L,"VEDACIT","DADOS","CTE:cte",
                "AVALIACAO","AGUARDANDO_ORIGEM","ESPERA_ACESSO_ORIGEM",LocalDateTime.of(2026,9,21,12,0),null);
        eventos.registrar(e); eventos.registrar(e);
        assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM dbo.tb_integracao_etapa_evento",Integer.class));
    }
    @Test void timeoutRecusaEPendenciaNormalSaoCategoriasDiferentes() {
        for(int i=1;i<=3;i++)log(i,"cte"+i,"nf"+i,"SUCESSO",null);
        jdbc.update("UPDATE dbo.tb_log_integracao SET status_canhoto='ERRO_DESTINO',canhoto_classificacao_operacional='TIMEOUT_AMBIGUO' WHERE id=1");
        jdbc.update("UPDATE dbo.tb_log_integracao SET status_canhoto='ERRO_DESTINO',canhoto_classificacao_operacional='BLOQUEADO_DESTINO' WHERE id=2");
        jdbc.update("UPDATE dbo.tb_log_integracao SET status_canhoto='PENDENTE_ENVIO' WHERE id=3");
        var pod=consultar().etapas().stream().filter(e->e.etapa().equals("COMPROVANTE")).findFirst().orElseThrow();
        assertEquals(1,pod.aguardandoConfirmacao()); assertEquals(1,pod.intervencao()); assertEquals(1,pod.aguardandoProcessamento());
    }
    @Test void sucessoDaIdentidadeEfetivaPrevaleceESemDataNaoViraPendente() {
        log(1,"cte","nf","SUCESSO",null);log(2,"cte","nf","ERRO_DESTINO","ORIGEM_XML_HTTP_401");
        jdbc.update("UPDATE dbo.tb_log_integracao SET status_canhoto='ERRO_DESTINO',canhoto_classificacao_operacional='TIMEOUT_AMBIGUO',canhoto_chave_cte_efetiva='efetivo'");
        jdbc.update("INSERT INTO dbo.tb_confirmacao_comprovante VALUES('nf','efetivo',NULL)");
        assertEquals(1,xml().sucessosPeriodo()); assertEquals(0,xml().aguardandoOrigem());
        var pod=consultar().etapas().stream().filter(e->e.etapa().equals("COMPROVANTE")).findFirst().orElseThrow();
        assertEquals(1,pod.confirmadosSemDataConfiavel()); assertEquals(0,pod.aguardandoConfirmacao());
    }
    @Test void detalhamentoMantemFiltroPaginacaoESemInventarIdadeHistorica() {
        for(int i=1;i<=28;i++) log(i,"cte"+i,"nf"+i,"ERRO_DESTINO","ORIGEM_XML_HTTP_401");
        var p=repository.pendencias(List.of("VEDACIT"),"DADOS","AGUARDANDO_ORIGEM",1,25);
        assertEquals(28,p.totalElementos());assertEquals(3,p.itens().size());assertNull(p.itens().get(0).pendenteDesde());
        assertNull(p.itens().get(0).proximaAvaliacao()); assertEquals("ACESSO_ORIGEM_RECUSADO",p.itens().get(0).motivo());
        assertEquals(0,repository.pendencias(List.of("PPG"),"DADOS","AGUARDANDO_ORIGEM",0,25).totalElementos());
    }
    @Test void cicloHistoricoMistoNaoViraFalhaTecnicaEGenericoNaoGanhaCausaInventada() {
        jdbc.execute("CREATE TABLE dbo.ciclo(resultado_execucao VARCHAR(40),fim_em TIMESTAMP,motivo_falha VARCHAR(200),conexao VARCHAR(20),status_ciclo VARCHAR(20),pendentes INT,xml_pendentes INT,erros_comprovante INT,xml_erros INT)");
        jdbc.update("INSERT INTO dbo.ciclo VALUES(NULL,'2026-09-21 17:40:59','XML_FALHAS_MISTAS: detalhes','OK','FALHA',1,0,0,5)");
        var sql="SELECT "+WorkSftpClientesAuditoriaRepository.RESULTADO_EXECUCAO+" FROM dbo.ciclo e";
        assertEquals("COM_PENDENCIAS",jdbc.queryForObject(sql,String.class));
        jdbc.update("UPDATE dbo.ciclo SET motivo_falha='PROCESSAMENTO: legado',erros_comprovante=1");
        assertEquals("NAO_CLASSIFICADO",jdbc.queryForObject(sql,String.class));
        jdbc.update("UPDATE dbo.ciclo SET motivo_falha='BANCO_FILA_PROCESSAMENTO: erro'");
        assertEquals("FALHA_TECNICA",jdbc.queryForObject(sql,String.class));
        jdbc.update("UPDATE dbo.ciclo SET fim_em=NULL");assertEquals("EM_EXECUCAO",jdbc.queryForObject(sql,String.class));
    }
}
